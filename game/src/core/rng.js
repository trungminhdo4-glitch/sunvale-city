// Seeded pseudo random numbers (mulberry32) so the city and screenshot scenes repeat exactly.

export function createRng(seed = 1) {
  let s = seed >>> 0;
  const next = () => {
    s = (s + 0x6d2b79f5) >>> 0;
    let t = s;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
  return {
    next,
    range: (a, b) => a + (b - a) * next(),
    int: (a, b) => Math.floor(a + (b - a + 1) * next()),
    pick: (arr) => arr[Math.floor(next() * arr.length)],
    chance: (p) => next() < p,
  };
}

/** The one gameplay RNG; reseeded by shot scenes. */
export const rng = createRng(Date.now() & 0xffff);

export function reseed(seed) {
  const fresh = createRng(seed);
  Object.assign(rng, fresh);
}
